test.describe('other pages', () => {
  test('auto-switch starts the child, streams events, saves config, stops', async () => {
    const { app, page, state } = await launch({ env: { FAKE_CSWAP_AUTO_INTERVAL: '0.3' } })
    await page.getByTestId('nav-auto').click()
    await page.getByTestId('auto-toggle').click()
    await expect(page.getByTestId('auto-toggle')).toContainText('Stop')
    await page.getByRole('button', { name: 'All' }).click()
    await expect(page.getByTestId('auto-feed')).toContainText('poll')
    await expect(page.getByTestId('auto-feed')).toContainText('sleep')
    await shot(page, 'auto-running')
    // config write goes through `cswap config set`
    const thr = page.getByTestId('cfg-autoswitch.threshold').getByRole('spinbutton')
    await thr.fill('80')
    await thr.press('Enter')
    await expect(page.getByRole('status').first()).toContainText('autoswitch.threshold = 80')
    expect(state().settings['autoswitch.threshold']).toBe(80)
    await page.getByTestId('auto-toggle').click()
    await expect(page.getByTestId('auto-toggle')).toContainText('Start')
    await expect(page.getByText(/Stopped|Exited/)).toBeVisible()
    await app.close()
  })

  test('mappings: add via the directory picker stub and unmap', async () => {
    const { app, state, statePath } = await launch()
    const stub = join(dirname(statePath), 'dialogs.json')
    writeFileSync(stub, JSON.stringify({ directory: '/tmp/picked-project' }))
    await app.close()
    const l2 = await launch({ env: { CSWAP_DESKTOP_TEST_DIALOGS: stub, FAKE_CSWAP_STATE: statePath } })
    await l2.page.getByTestId('nav-mappings').click()
    await expect(l2.page.getByTestId('mapping-row')).toHaveCount(1)
    await l2.page.getByTestId('map-add').click()
    await l2.page.getByRole('button', { name: 'Browse' }).click()
    await expect(l2.page.getByTestId('map-path')).toHaveValue('/tmp/picked-project')
    await l2.page.getByTestId('map-account').selectOption('2')
    await shot(l2.page, 'dialog-map')
    await l2.page.getByTestId('map-submit').click()
    await expect(l2.page.getByTestId('mapping-row')).toHaveCount(2)
    expect(state().mappings['/tmp/picked-project']).toMatchObject({ email: 'work@company.com' })
    await l2.page.getByTestId('unmap').first().click()
    await expect(l2.page.getByTestId('mapping-row')).toHaveCount(1)
    await l2.app.close()
  })

  test('settings persist across restarts (theme + refresh interval) and the log page lists calls', async () => {
    const { app, page, userData } = await launch()
    await page.getByTestId('nav-settings').click()
    await page.getByRole('radio', { name: 'Dark' }).click()
    await page.getByRole('combobox', { name: 'Refresh interval' }).selectOption('300')
    await expect(page.locator('html')).toHaveClass(/dark/)
    await app.close()
    const saved = JSON.parse(readFileSync(join(userData, 'settings.json'), 'utf8'))
    expect(saved).toMatchObject({ theme: 'dark', refreshSeconds: 300 })
    const l2 = await launch({ settings: saved })
    await expect(l2.page.locator('html')).toHaveClass(/dark/)
    await l2.page.getByTestId('nav-log').click()
    await expect(l2.page.getByTestId('log-row').first()).toContainText('cswap')
    await l2.page.getByTestId('log-row').first().click()
    await shot(l2.page, 'log-dark-expanded')
    await l2.app.close()
  })

  test('without cswap the onboarding screen shows and a custom path recovers', async () => {
    const { app, page } = await launch({ bin: '/definitely/not/here/cswap' })
    await expect(page.getByTestId('onboarding')).toBeVisible()
    await expect(page.getByTestId('sidebar-status')).toContainText('not found')
    await shot(page, 'onboarding')
    await page.getByTestId('nav-settings').click()
    await page.getByTestId('cswap-path').fill(process.platform === 'win32' ? join(process.cwd(), 'test', 'fake-cswap', 'fake-cswap.cmd') : join(process.cwd(), 'test', 'fake-cswap', 'fake-cswap.mjs'))
    await page.getByTestId('cswap-path-save').click()
    await expect(page.getByTestId('sidebar-status')).toContainText('cswap 0.25.0')
    await page.getByTestId('nav-accounts').click()
    await expect(page.getByTestId('accounts-table')).toBeVisible()
    await app.close()
  })
})
